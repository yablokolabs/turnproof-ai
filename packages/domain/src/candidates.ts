/**
 * Candidate generation. Deterministic and rule-based: no model is involved in
 * deciding what counts as a candidate. Candidates only describe *allowed*
 * changes; feasibility is decided separately in `validate.ts`.
 */
import type { Snapshot } from './normalize.js';
import type { Candidate, Policy } from './schemas.js';
import { MINUTE_MS, toEpoch } from './time.js';

export type DisruptionFocus = { taskId: string; shiftMinutes: number };

/** The task whose reported revision moved furthest from its planned start. */
export function disruptionFocus(snapshot: Snapshot): DisruptionFocus | null {
  let best: DisruptionFocus | null = null;
  for (const task of snapshot.tasks) {
    const revised = task.earliestStart ?? task.plannedStart;
    const shift = Math.round((toEpoch(revised) - toEpoch(task.plannedStart)) / MINUTE_MS);
    if (shift <= 0) continue;
    if (
      best === null ||
      shift > best.shiftMinutes ||
      (shift === best.shiftMinutes && task.id < best.taskId)
    ) {
      best = { taskId: task.id, shiftMinutes: shift };
    }
  }
  return best;
}

function byId(a: { id: string }, b: { id: string }): number {
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

export function generateCandidates(snapshot: Snapshot, policy: Policy): Candidate[] {
  const candidates: Candidate[] = [];
  const focus = disruptionFocus(snapshot);
  const fallbackTask =
    snapshot.tasks.find((t) => t.resourceKind && t.status !== 'complete') ?? snapshot.tasks[0];
  const waitTaskId = focus?.taskId ?? fallbackTask.id;

  candidates.push({
    id: `wait:${waitTaskId}:baseline`,
    action: 'wait',
    taskId: waitTaskId,
    evidenceIds: [],
    assumptions: [
      'No new resource is introduced.',
      'The reported delay is absorbed by the existing plan.',
    ],
    estimatedCostUnits: policy.costUnits.wait,
  });

  const taskById = new Map(snapshot.tasks.map((t) => [t.id, t]));
  const focusTask = focus ? taskById.get(focus.taskId) : undefined;
  const alternateTargets = focusTask
    ? [focusTask]
    : snapshot.tasks.filter((t) => t.resourceKind && t.status !== 'complete');

  const resources = [...snapshot.resources].sort(byId);

  for (const task of alternateTargets) {
    if (!task.resourceKind) continue;
    for (const resource of resources) {
      if (resource.kind !== task.resourceKind) continue;
      if (resource.id === task.resourceId) continue;
      candidates.push({
        id: `use_alternate_resource:${task.id}:${resource.id}`,
        action: 'use_alternate_resource',
        taskId: task.id,
        resourceId: resource.id,
        evidenceIds: [...resource.evidenceIds],
        assumptions: [
          `Assumes ${resource.id} (${resource.kind}) can serve task ${task.id} (${task.kind}) under synthetic policy ${policy.version}.`,
          `Assumes availability reported at ${resource.availableFrom} holds for the whole task window.`,
        ],
        estimatedCostUnits: policy.costUnits.use_alternate_resource,
      });
    }
  }

  return candidates.sort(byId);
}

/**
 * Resequencing is a declared action but is not generated by this prototype:
 * the hero scope contains no reorderable independent tasks whose reorder
 * changes readiness. Recorded here so the gap is explicit rather than implied.
 */
export const GENERATED_ACTIONS: ReadonlyArray<Candidate['action']> = [
  'wait',
  'use_alternate_resource',
];
export const UNIMPLEMENTED_ACTIONS: ReadonlyArray<Candidate['action']> = ['resequencing'];
